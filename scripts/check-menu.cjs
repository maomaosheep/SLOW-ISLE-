const assert = require('node:assert/strict');
const cart = require('../miniprogram/utils/cart');
const plain = { id: 1, name: '芝士蛋糕', price: '28.00', options: {} };
const coffee = { id: 2, name: '拿铁', price: '26.00', options: { temperature: [{ label: '热' }, { label: '冰' }] } };
const app = {
  globalData: { cart: [] },
  setCart(items) { this.globalData.cart = items; },
  addToCart(product, options, quantity) { this.setCart(cart.add(this.globalData.cart, cart.lineFor(product, options, quantity))); }
};
const notices = [], destinations = [];
global.getApp = () => app;
global.wx = { showToast: value => notices.push(value), navigateTo: value => destinations.push(value.url) };
let page;
global.Page = definition => { page = { ...definition, data: structuredClone(definition.data), setData(data) { Object.assign(this.data, data); } }; };
require('../miniprogram/pages/menu/index');
page.setData({ store: { is_open: true }, products: [plain, coffee] });
const adjust = (id, delta) => page.adjustProduct({ currentTarget: { dataset: { id, delta } } });
adjust(1, 1);
assert.equal(page.data.productCounts[1], 1);
adjust(1, 1);
assert.equal(page.data.productCounts[1], 2);
assert.equal(page.data.total, '56.00');
adjust(1, -1);
assert.equal(page.data.productCounts[1], 1);
adjust(1, -1);
assert.equal(page.data.productCounts[1], undefined);
assert.equal(page.data.count, 0);
adjust(2, 1);
assert.deepEqual(destinations, ['/pages/detail/index?id=2'], 'First coffee opens specification selection');
assert.equal(page.data.count, 0);
app.addToCart(coffee, { temperature: '冰' }, 1);
page.syncCart();
adjust(2, 1);
assert.equal(page.data.productCounts[2], 2);
assert.equal(app.globalData.cart[0].options.temperature, '冰', 'Quick add preserves the selected specification');
app.addToCart(coffee, { temperature: '热' }, 1);
page.syncCart();
assert.equal(page.data.productCounts[2], 3, 'Menu count combines the same product across specifications');
const before = structuredClone(app.globalData.cart);
adjust(2, -1);
assert.equal(page.data.bagVisible, true);
assert.deepEqual(app.globalData.cart, before, 'Multiple specifications must be adjusted explicitly');
adjust(2, 1);
assert.equal(destinations.length, 2, 'Multiple specifications reopen selection for adding');
assert.deepEqual(app.globalData.cart, before);
app.setCart([cart.lineFor(plain, {}, 20)]);
page.syncCart();
adjust(1, 1);
assert.equal(page.data.productCounts[1], 20);
page.changeBag({ detail: { key: app.globalData.cart[0].key, delta: 1 } });
assert.equal(page.data.count, 20, 'Bag and menu use the same quantity limit');
page.data.store.is_open = false;
adjust(1, 1);
assert.equal(page.data.count, 20);
adjust(1, -1);
assert.equal(page.data.count, 19, 'Closed store still allows removing items');
const bulk = [1, 2, 3].map((id, index) => cart.lineFor({ ...plain, id }, {}, index === 2 ? 10 : 20));
assert.throws(() => cart.change(bulk, bulk[2].key, 1), /50/);
assert.equal(cart.totals(bulk).count, 50, 'Rejected quantity changes leave the original cart intact');
assert.ok(notices.length >= 3);
console.log('Passed menu quantities: initial add, specification selection/reuse, aggregate counts, subtract to zero, multiple variants, closed store, shared limits and stable totals.');
